    public static int subOrder(String cat, String sub) {
        Integer v = SUB_ORDER.get(cat + "\u0000" + sub);
        return v == null ? 999 : v;
    }

    /** 某大类的全部小类名（按表内顺序） */
    public static java.util.List<String> subsOf(String cat) {
        java.util.List<String> out = new java.util.ArrayList<>();
        for (Map.Entry<String, Integer> e : SUB_ORDER.entrySet()) {
            String k = e.getKey();
            int i = k.indexOf('\u0000');
            if (i > 0 && k.substring(0, i).equals(cat)) out.add(k.substring(i + 1));
        }
        out.sort((a, b) -> Integer.compare(subOrder(cat, a), subOrder(cat, b)));
        return out;
    }
